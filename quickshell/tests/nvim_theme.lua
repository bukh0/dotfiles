-- Run with an isolated Neovim config/data/state copy; this test changes theme state.
local theme = require('utils.theme')
local state = require('utils.state')
vim.wait(300)
vim.api.nvim_exec_autocmds('User', {pattern='VeryLazy'})
vim.wait(300)
local function wait() vim.wait(350) end
local function expect(value, expected)
  assert(value == expected, vim.inspect({actual=value,expected=expected}))
end
vim.cmd.colorscheme('monokai-pro-spectrum')
wait()
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
local picker = theme.pick_colorscheme({pattern='vague'})
wait()
expect(vim.g.colors_name, 'vague')
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
picker:close()
wait()
expect(vim.g.colors_name, 'monokai-pro')
expect(require('monokai-pro.config').get().filter, 'spectrum')
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
print('PASS preview does not persist; cancel restores exact variant')
picker = theme.pick_colorscheme({pattern='vague'})
wait()
picker.opts.confirm(picker, {text='vague'})
wait()
expect(vim.g.colors_name, 'vague')
expect(state.read('colorscheme.state'), 'vague')
print('PASS confirm persists selection')
picker = theme.pick_colorscheme({pattern='monokai-pro-spectrum'})
wait()
picker.opts.confirm(picker, {text='monokai-pro-spectrum'})
wait()
expect(require('monokai-pro.config').get().filter, 'spectrum')
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
theme.set_transparent(not theme.transparent)
wait()
expect(require('monokai-pro.config').get().filter, 'spectrum')
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
print('PASS confirmed variant survives transparency reload')
picker = theme.pick_colorscheme({pattern='nonexistent-theme-test'})
picker:close()
wait()
expect(state.read('colorscheme.state'), 'monokai-pro-spectrum')
print('PASS immediate cancel and empty results')
picker = theme.pick_colorscheme({pattern='monokai-pro-spectrum'})
wait()
picker:close()
wait()
vim.cmd.colorscheme('vague')
wait()
picker = Snacks.picker.resume({source='colorschemes'})
wait()
expect(vim.g.colors_name, 'monokai-pro')
expect(state.read('colorscheme.state'), 'vague')
picker:close()
wait()
expect(vim.g.colors_name, 'vague')
expect(state.read('colorscheme.state'), 'vague')
print('PASS resumed picker restores current theme')
vim.cmd('qa!')
